using System;
using UnityEngine;

namespace Common
{
    /// <summary>
    /// 타격/시전 이펙트의 "재생"이 구현하는 계약. <see cref="HitEffectSpawner"/>는 이펙트가 얼마나 긴지
    /// 알 필요가 없고, 수명을 스스로 재지도 않는다 - 오직 이 인터페이스의 완료 통보를 받고서야 풀로
    /// 회수한다. 그래서 6프레임짜리든 20프레임짜리든 <b>이펙트는 항상 마지막 프레임까지 재생된 뒤에
    /// 사라진다</b>(스포너의 기본 수명 값과 클립 길이가 어긋나 중간에 잘리던 문제의 근본 원인 제거).
    ///
    /// 길이는 이펙트 자신만이 아는 정보이므로 여기가 단일 소스다 - 공격 모션 데이터에 길이를 따로 적어
    /// 두지 않는다. 클립을 6프레임에서 8프레임으로 늘려도 그 이펙트를 참조하는 모션 데이터는 하나도
    /// 고칠 필요가 없다.
    ///
    /// 재생 중에 다음 이펙트가 또 생성되는 것은 정상이다 - 스포너가 인스턴스를 prefab별로 풀링하므로
    /// 겹쳐서 여러 개가 동시에 재생돼도 서로 간섭하지 않는다. 겹침을 기능적으로 막는 책임은 이 계약에
    /// 없다(연출상 어색한지는 작업자가 데이터로 조절할 부분이다).
    ///
    /// 구현체는 이펙트 루트에 있어도 되고 자식 오브젝트에 있어도 된다(스포너가
    /// GetComponentInChildren으로 찾는다). 풀에서 재사용되므로 <see cref="Play"/>는 반드시 이전 재생
    /// 상태를 처음부터 다시 시작시켜야 한다 - 직전 재생의 마지막 프레임이 한 프레임이라도 노출되면 안 된다.
    /// </summary>
    public interface IHitEffectPlayback
    {
        /// <summary>이 이펙트가 처음부터 끝까지 재생되는 데 걸리는 시간(초). 재생 상태와 무관하게 항상
        /// 같은 값을 돌려주는 순수 조회이며, 프리팹 에셋 위에서(인스턴스가 아닌 상태에서) 읽어도
        /// 안전해야 한다 - 모션 에디터 프리뷰가 프리팹을 직접 들고 이 값을 묻는다.</summary>
        float Duration { get; }

        /// <summary>재생을 처음부터 (재)시작한다. scaleMultiplier는 공격 모션 데이터의 Effect Scale로,
        /// 프리팹 원본 배율에 곱해진다(0 이하는 1로 보정). 재생이 끝나면 onComplete에 자기 자신을 넘긴다 -
        /// 스포너는 이걸 받아 풀로 회수한다. onComplete가 null이면 스포너 없이 단독으로 놓인 경우이므로
        /// 스스로 정리한다.</summary>
        void Play(float scaleMultiplier, Action<IHitEffectPlayback> onComplete);

        /// <summary>재생 시작 후 elapsed초 시점에 보여야 할 Sprite를 돌려주는 순수 조회 - 재생 상태를
        /// 전혀 바꾸지 않고, 프리팹 에셋 위에서 호출해도 안전하다. 모션 에디터 프리뷰가 타임라인을
        /// 스크럽하며 런타임과 같은 그림을 그리는 데 쓴다. elapsed가 <see cref="Duration"/> 이상이면
        /// (= 이미 사라졌어야 하면) null을 돌려준다.</summary>
        Sprite GetFrameAt(float elapsed);
    }
}
